
import mimetypes

from django.conf import settings
from django.conf.urls.static import static
from django.contrib import admin
from django.http import FileResponse, HttpResponseNotFound
from django.urls import include, path, re_path


def frontend_index(request):
    index_file = settings.FRONTEND_DIST_DIR / "index.html"

    if not index_file.is_file():
        return HttpResponseNotFound(
            "Frontend build not found. Build the React frontend first."
        )

    return FileResponse(
        index_file.open("rb"),
        content_type="text/html",
    )


def frontend_asset(request, asset_path):
    """
    Serve files generated by the React production build,
    including product images, JavaScript, CSS, and other assets.
    """
    frontend_dir = settings.FRONTEND_DIST_DIR.resolve()
    asset_file = (frontend_dir / asset_path).resolve()

    # Prevent paths from accessing files outside the frontend build.
    if not asset_file.is_relative_to(frontend_dir):
        return HttpResponseNotFound("File not found.")

    if not asset_file.is_file():
        return HttpResponseNotFound("File not found.")

    content_type, _ = mimetypes.guess_type(str(asset_file))

    return FileResponse(
        asset_file.open("rb"),
        content_type=content_type or "application/octet-stream",
    )


def frontend_logo(request):
    return frontend_asset(request, "logo.jpeg")


urlpatterns = [
    # Django administration.
    path("admin/", admin.site.urls),

    # Backend API endpoints.
    path("api/", include("products.urls")),
    path("api/", include("orders.urls")),

    # Explicit frontend logo endpoint.
    path("logo.jpeg", frontend_logo, name="frontend-logo"),

    # Serve actual built files before the React SPA fallback.
    re_path(
        r"^(?P<asset_path>(?!api/|admin/|static/|media/).+\.[^/]+)$",
        frontend_asset,
        name="frontend-asset",
    ),

    # React application entry point.
    path("", frontend_index, name="frontend"),

    # React client-side routes, such as product and order pages.
    re_path(
        r"^(?!api/|admin/|static/|media/).+",
        frontend_index,
        name="frontend-spa-fallback",
    ),
]

if settings.DEBUG:
    urlpatterns += static(
        settings.MEDIA_URL,
        document_root=settings.MEDIA_ROOT,
    )
